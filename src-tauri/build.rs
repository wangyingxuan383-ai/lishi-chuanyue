fn main() {
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .plugin(
                "notifications",
                tauri_build::InlinedPlugin::new().commands(&[
                    "request_notification_permission",
                    "notification_status",
                    "open_notification_settings",
                    "open_app_settings",
                    "story_committed",
                    "set_keep_awake",
                    "open_url",
                    "set_system_bars",
                    "haptic",
                ]),
            )
            .plugin(
                "updates",
                tauri_build::InlinedPlugin::new().commands(&[
                    "download",
                    "cancel",
                    "fetch_text",
                    "install",
                    "can_install",
                    "dev_source",
                    "set_dev_source",
                ]),
            ),
    )
    .expect("Tauri build failed")
}
