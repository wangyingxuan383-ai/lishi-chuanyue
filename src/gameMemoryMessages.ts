export type MemoryMessageKey = keyof typeof messages;
type Placeholders<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | Placeholders<Rest> : never;
export type MemoryPlainMessageKey = { [Key in MemoryMessageKey]: Placeholders<(typeof messages)[Key]> extends never ? Key : never }[MemoryMessageKey];
type Args<Key extends MemoryMessageKey> = [Placeholders<(typeof messages)[Key]>] extends [never]
  ? [] : [values: Record<Placeholders<(typeof messages)[Key]>, string | number>];

export function memoryT<Key extends MemoryMessageKey>(key: Key, ...args: Args<Key>): string {
  const values = args[0] as Record<string, string | number> | undefined;
  return messages[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) => values?.[name] === undefined ? placeholder : String(values[name]));
}
