export type GameMessageKey = keyof typeof gameMessages;
type PlaceholderNames<Text extends string> = Text extends `${string}{${infer Name}}${infer Rest}`
  ? Name | PlaceholderNames<Rest> : never;
type TranslationArgs<Key extends GameMessageKey> = [PlaceholderNames<(typeof gameMessages)[Key]>] extends [never]
  ? [] : [params: Record<PlaceholderNames<(typeof gameMessages)[Key]>, string | number>];

export function gameT<Key extends GameMessageKey>(key: Key, ...args: TranslationArgs<Key>): string {
  const params = args[0] as Record<string, string | number> | undefined;
  return gameMessages[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) =>
    params?.[name] === undefined ? placeholder : String(params[name]));
}
