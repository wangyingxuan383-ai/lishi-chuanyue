export type ModelMessageKey = keyof typeof modelMessages;

type PlaceholderNames<Text extends string> =
  Text extends `${string}{${infer Name}}${infer Remaining}`
    ? Name | PlaceholderNames<Remaining>
    : never;

type TranslationArgs<Key extends ModelMessageKey> =
  [PlaceholderNames<(typeof modelMessages)[Key]>] extends [never]
    ? []
    : [params: Record<PlaceholderNames<(typeof modelMessages)[Key]>, string | number>];

export function modelT<Key extends ModelMessageKey>(key: Key, ...args: TranslationArgs<Key>): string {
  const params = args[0] as Record<string, string | number> | undefined;
  return modelMessages[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) => {
    const value = params?.[name];
    return value === undefined ? placeholder : String(value);
  });
}
