export type BranchMessageKey = keyof typeof messages;
type Placeholders<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | Placeholders<Rest> : never;
export type BranchPlainMessageKey = { [Key in BranchMessageKey]: Placeholders<(typeof messages)[Key]> extends never ? Key : never }[BranchMessageKey];
type Args<Key extends BranchMessageKey> = [Placeholders<(typeof messages)[Key]>] extends [never] ? [] : [values: Record<Placeholders<(typeof messages)[Key]>, string | number>];
export function branchT<Key extends BranchMessageKey>(key: Key, ...args: Args<Key>): string {
  const values = args[0] as Record<string, string | number> | undefined;
  return messages[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) => values?.[name] === undefined ? placeholder : String(values[name]));
}
