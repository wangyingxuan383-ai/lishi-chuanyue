export default function Guide() {
  const { pop } = useApp();
  const [open, setOpen] = useState<Record<string, boolean>>({ start: true });
  return (
    <div className="screen">
      <div className="topbar">
        <button className="icon-btn" aria-label="返回" onClick={pop}><Icon name="back" /></button>
        <div className="title"><h1>游玩指南</h1></div>
      </div>
      <div className="screen-body stack guide">
        {SECTIONS.map((s) => (
          <section key={s.id} className={`fold${open[s.id] ? " open" : ""}`}>
            <button className="fold-head" aria-expanded={!!open[s.id]} onClick={() => setOpen((o) => ({ ...o, [s.id]: !o[s.id] }))}>
              <span><b>{s.title}</b></span><span aria-hidden="true">{open[s.id] ? "收起" : "展开"}</span>
            </button>
            {open[s.id] && <div className="fold-body guide-body">
              {s.body.map(([k, v], i) => <p key={i}>{k && <b>{k}　</b>}{v}</p>)}
            </div>}
          </section>
        ))}
        <p className="muted" style={{ textAlign: "center" }}>有问题或建议，可以在 设置 → 关于与更新 里提交。</p>
      </div>
    </div>
  );
}
