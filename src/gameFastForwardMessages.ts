export type FastForwardMessageKey = keyof typeof messages;
type Placeholders<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | Placeholders<Rest> : never;
export type FastForwardPlainMessageKey = { [Key in FastForwardMessageKey]: Placeholders<(typeof messages)[Key]> extends never ? Key : never }[FastForwardMessageKey];
type Args<Key extends FastForwardMessageKey> = [Placeholders<(typeof messages)[Key]>] extends [never] ? [] : [values: Record<Placeholders<(typeof messages)[Key]>, string | number>];
export function fastForwardT<Key extends FastForwardMessageKey>(key: Key, ...args: Args<Key>): string {
  const values = args[0] as Record<string, string | number> | undefined;
  return messages[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) => values?.[name] === undefined ? placeholder : String(values[name]));
}
