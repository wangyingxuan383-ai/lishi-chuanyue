// True-novel formatter & chaptered book builder (R35-T004).
// Converts a world's active path into an immersion-first classical Chinese
// chaptered novel (章回体小说), stripping raw command echoes by default,
// preserving write-mode prose, auto-chaptering uncovered turns, and adding
// optional 列传 frontmatter and chronicle appendix.
import { cnNumber } from "./book";
import { nowOf, type GameClock } from "./calendar/clock";
import { season } from "./calendar/date";
import type { Repo } from "./db/repo";
import { eraContext, worldClock } from "./era";
import { dateText, lifeSeal, lifeSummary, type LifeSeal } from "./life";
import type { TurnRecord } from "./state/apply";
import { parseNovelProseBlocks } from "./text/proseClean";
import type { Chapter, Person, StoryNode, World, WorldState } from "./types";

export interface NovelOptions {
  /** Include player `do` / `say` / `skip` prompts as `kind: "action"` blocks. Default: `false`. */
  includeActions?: boolean;
  /** Include frontmatter character & backstory introduction (`卷首 · 人物与前情`). Default: `true`. */
  includePreface?: boolean;
  /** Include chronological appendix (`附录 · 本局大事纪年`). Default: `true`. */
  includeChronicle?: boolean;
  /** Target turns per auto-generated chapter for uncovered passages (default `10`, min `6`). */
  chapterEvery?: number;
  /** Optional specific branch/line ID; defaults to `world.currentLineId`. */
  lineId?: string;
}

export type NovelParagraphKind = "prose" | "divider" | "action";

export interface NovelParagraph {
  kind: NovelParagraphKind;
  text: string;
  nodeId?: string | null;
}

export type NovelSectionKind = "preface" | "prologue" | "chapter" | "appendix";

export interface NovelSection {
  index: number;
  kind: NovelSectionKind;
  title: string;
  subtitle?: string;
  chapterNumber?: number | null;
  autoGenerated?: boolean;
  firstNodeId?: string | null;
  lastNodeId?: string | null;
  paragraphs: NovelParagraph[];
  chars: number;
}

export type NovelStatusLine =
  | "—— 全书完 · 这一世终 ——"
  | "—— 本卷完 ——"
  | "—— 未完待续 ——";

export interface NovelBook {
  worldId: string;
  lineId: string;
  lineName: string;
  title: string;
  subtitle: string;
  author: string;
  eraTitle: string;
  seal: LifeSeal;
  statusLine: NovelStatusLine;
  generatedAt: string;
  turnCount: number;
  chapterCount: number;
  totalChars: number;
  sections: NovelSection[];
}

const FULLWIDTH_INDENT = "　　";

const ensureSentence = (text: string) => {
  const t = text.trim();
  if (!t) return "";
  return /[。！？…」』”]$/.test(t) ? t : `${t}。`;
};

function firstSentence(text: string, max = 96): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (!clean) return "";
  if (clean.length <= max) return ensureSentence(clean);
  const head = clean.slice(0, max);
  const cut = Math.max(head.lastIndexOf("。"), head.lastIndexOf("！"), head.lastIndexOf("？"));
  return cut >= max * 0.45 ? head.slice(0, cut + 1) : `${head}……`;
}

function splitProseLines(text: string, nodeId?: string | null): NovelParagraph[] {
  return parseNovelProseBlocks(text)
    .map((b) =>
      b.kind === "divider"
        ? { kind: "divider" as const, text: "◇", ...(nodeId !== undefined ? { nodeId } : {}) }
        : {
            kind: "prose" as const,
            text: b.text.replace(/^[\s\u3000]+|[\s\u3000]+$/g, ""),
            ...(nodeId !== undefined ? { nodeId } : {}),
          },
    )
    .filter((p) => Boolean(p.text));
}

function stripChapterPrefix(rawTitle: string): string {
  return rawTitle
    .trim()
    .replace(/^第\s*[零〇一二三四五六七八九十百千万两\d]+\s*[章节回][\s\u3000·：:—\-]*/, "")
    .trim();
}

function formatChapterHeading(chapterNum: number, rawTitle?: string): string {
  const clean = rawTitle ? stripChapterPrefix(rawTitle) : "";
  return clean ? `第${cnNumber(chapterNum)}回 · ${clean}` : `第${cnNumber(chapterNum)}回`;
}

interface NodeTimelineMeta {
  minutes: number;
  clock: GameClock;
  dateLabel: string;
  dayNumber: number;
  hour: number;
  shichen: string;
  seasonChar: string | null;
  place: string | null;
  placeChanged: boolean;
}

function computeNodeMeta(
  world: World,
  path: StoryNode[],
  headState: WorldState,
  openingState: WorldState,
  clocks: Map<string, Pick<WorldState, "time" | "era">>,
): Map<string, NodeTimelineMeta> {
  const fallbackClock = worldClock(world.eraId, headState);
  let currentPlace: string | null =
    openingState.places.find((p) => p.id === openingState.placeId)?.name ??
    openingState.places[0]?.name ??
    null;

  const metaByNode = new Map<string, NodeTimelineMeta>();

  for (const node of path) {
    const rec = (node.record && typeof node.record === "object" ? (node.record as TurnRecord) : null);
    const nextPlace = typeof rec?.place === "string" && rec.place.trim() ? rec.place.trim() : null;
    const placeChanged = Boolean(nextPlace && nextPlace !== currentPlace);
    if (nextPlace) currentPlace = nextPlace;

    const snap = clocks.get(node.id);
    const minutes = snap
      ? snap.time.elapsedMinutes
      : node.kind === "opening"
        ? 0
        : node.id === path.at(-1)?.id
          ? headState.time.elapsedMinutes
          : 0;
    const nodeClock = snap ? worldClock(world.eraId, snap) : fallbackClock;
    const now = nowOf(nodeClock, minutes);
    metaByNode.set(node.id, {
      minutes,
      clock: nodeClock,
      dateLabel: dateText(nodeClock, minutes),
      dayNumber: now.day,
      hour: now.hour,
      shichen: now.shichen,
      seasonChar: now.date ? season(now.date) : null,
      place: currentPlace,
      placeChanged,
    });
  }

  return metaByNode;
}

function deriveAutoChapterTitle(
  chapterNum: number,
  nodes: StoryNode[],
  metaByNode: Map<string, NodeTimelineMeta>,
  usedShortTitles: Set<string>,
): string {
  const firstMeta = metaByNode.get(nodes[0]?.id ?? "");
  const lastMeta = metaByNode.get(nodes.at(-1)?.id ?? "");

  // Find primary or newly entered place in this slice.
  let enteredPlace: string | null = null;
  const placeCounts = new Map<string, number>();
  let featuredPerson: string | null = null;

  for (const n of nodes) {
    const m = metaByNode.get(n.id);
    if (m?.placeChanged && m.place && !enteredPlace) enteredPlace = m.place;
    if (m?.place) placeCounts.set(m.place, (placeCounts.get(m.place) ?? 0) + 1);
    const rec = n.record && typeof n.record === "object" ? (n.record as TurnRecord) : null;
    if (!featuredPerson && Array.isArray(rec?.people)) {
      const p = rec.people.find((item) => item && item.op !== "remove" && typeof item.name === "string" && item.name.trim());
      if (p) featuredPerson = p.name.trim();
    }
  }

  const dominantPlace =
    enteredPlace ??
    [...placeCounts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ??
    firstMeta?.place ??
    lastMeta?.place ??
    null;

  const shortPlace = dominantPlace ? dominantPlace.slice(0, 6) : null;
  const sc = firstMeta?.shichen ?? "辰";
  const seasonWord = firstMeta?.seasonChar ?? "";
  const isNight = firstMeta ? firstMeta.hour >= 19 || firstMeta.hour < 5 : false;
  const isDawn = firstMeta ? firstMeta.hour >= 5 && firstMeta.hour < 8 : false;
  const isDusk = firstMeta ? firstMeta.hour >= 17 && firstMeta.hour < 19 : false;
  const timeMood = isNight ? "夜话" : isDawn ? "晨光" : isDusk ? "暮色" : `${sc}时`;

  const candidates: string[] = [];
  if (shortPlace) {
    if (chapterNum === 1) {
      candidates.push(`初入${shortPlace}`, `${shortPlace}初逢`, `${shortPlace}${timeMood}`);
    } else if (enteredPlace) {
      candidates.push(`行至${shortPlace}`, `初至${shortPlace}`, `风起${shortPlace}`, `${shortPlace}${timeMood}`);
    } else {
      candidates.push(
        `风起${shortPlace}`,
        `${shortPlace}${timeMood}`,
        seasonWord ? `${shortPlace}${seasonWord}深` : `${shortPlace}风云`,
        featuredPerson ? `${shortPlace}逢${featuredPerson.slice(0, 3)}` : `${shortPlace}暗流`,
        `再探${shortPlace}`,
        `${shortPlace}纪事`,
      );
    }
  }

  if (firstMeta?.dateLabel) {
    const compactDate = firstMeta.dateLabel.replace(/\s+/g, "");
    candidates.push(
      seasonWord ? `${seasonWord}日${timeMood}` : `${compactDate.slice(-6)}`,
      `${compactDate}${sc}时`,
    );
  }
  candidates.push(`世路第${cnNumber(chapterNum)}程`);

  const picked = candidates.find((c) => c && !usedShortTitles.has(c)) ?? `${candidates[0]}（${cnNumber(chapterNum)}）`;
  usedShortTitles.add(picked);
  return picked;
}

function actionLineForNode(node: StoryNode): string | null {
  const clean = node.actionText?.replace(/\s+/g, " ").trim();
  if (!clean || node.kind === "opening") return null;
  switch (node.actionMode) {
    case "do":
      return `你：${clean}`;
    case "say":
      return `你说：${clean}`;
    case "skip":
      return `过些日子：${clean}`;
    default:
      return null;
  }
}

function transitionDividerBetween(
  prev: StoryNode,
  curr: StoryNode,
  metaByNode: Map<string, NodeTimelineMeta>,
): NovelParagraph | null {
  const prevMeta = metaByNode.get(prev.id);
  const currMeta = metaByNode.get(curr.id);
  const isSkip = curr.kind === "fastforward" || curr.actionMode === "skip";

  if (!prevMeta || !currMeta) {
    return isSkip ? { kind: "divider", text: "◇", nodeId: curr.id } : null;
  }

  const minuteDelta = currMeta.minutes - prevMeta.minutes;
  const dayDelta = currMeta.dayNumber - prevMeta.dayNumber;
  const dateChanged = currMeta.dateLabel !== prevMeta.dateLabel && Boolean(currMeta.dateLabel);

  if (isSkip) {
    const labelParts = [
      dateChanged ? currMeta.dateLabel : "",
      currMeta.placeChanged && currMeta.place ? currMeta.place : "",
    ].filter(Boolean);
    return {
      kind: "divider",
      text: labelParts.length ? labelParts.join(" · ") : "◇",
      nodeId: curr.id,
    };
  }

  if (dayDelta >= 2 || minuteDelta >= 1440) {
    const label = currMeta.placeChanged && currMeta.place
      ? `${currMeta.dateLabel} · ${currMeta.place}`
      : currMeta.dateLabel || "◇";
    return { kind: "divider", text: label, nodeId: curr.id };
  }

  if (dayDelta >= 1 && currMeta.placeChanged && currMeta.place) {
    return { kind: "divider", text: `${currMeta.dateLabel} · ${currMeta.place}`, nodeId: curr.id };
  }

  if (minuteDelta >= 720 || (currMeta.placeChanged && minuteDelta >= 240)) {
    return {
      kind: "divider",
      text: currMeta.placeChanged && currMeta.place ? `${currMeta.place} · ${currMeta.shichen}时` : "◇",
      nodeId: curr.id,
    };
  }

  return null;
}

function buildSectionParagraphs(
  nodes: StoryNode[],
  metaByNode: Map<string, NodeTimelineMeta>,
  includeActions: boolean,
): NovelParagraph[] {
  const paragraphs: NovelParagraph[] = [];
  let prevRenderedNode: StoryNode | null = null;

  for (const node of nodes) {
    const nodeBlocks: NovelParagraph[] = [];

    if (node.actionMode === "write" && node.actionText?.trim()) {
      nodeBlocks.push(...splitProseLines(node.actionText, node.id));
    } else if (includeActions) {
      const act = actionLineForNode(node);
      if (act) nodeBlocks.push({ kind: "action", text: act, nodeId: node.id });
    }

    if (node.narrative.trim()) {
      nodeBlocks.push(...splitProseLines(node.narrative, node.id));
    }

    if (!nodeBlocks.length) continue;

    if (prevRenderedNode) {
      const divider = transitionDividerBetween(prevRenderedNode, node, metaByNode);
      if (divider) paragraphs.push(divider);
    }

    paragraphs.push(...nodeBlocks);
    prevRenderedNode = node;
  }

  return paragraphs;
}

const ATTITUDE_WEIGHT: Record<Person["attitude"], number> = {
  生死之交: 6,
  亲近: 5,
  友善: 4,
  仇视: 4,
  敌意: 3,
  一般: 2,
  冷淡: 1,
};

function buildPrefaceSection(
  index: number,
  state: WorldState,
  headClock: GameClock,
  eraTitle: string,
  currency: ReturnType<typeof eraContext>["currency"],
  dead: boolean,
): NovelSection {
  const summary = lifeSummary({ state, clock: headClock, currency, eraTitle, dead });
  const paragraphs: NovelParagraph[] = [];

  for (const sec of summary.sections) {
    if (sec.label === "出身" || sec.label === "生平" || sec.label === "经历" || sec.label === "足迹") {
      paragraphs.push({ kind: "prose", text: sec.text, nodeId: null });
    }
  }

  if (state.people.length > 0) {
    const ranked = [...state.people].sort((a, b) => {
      const aliveDiff = Number(b.alive !== false) - Number(a.alive !== false);
      if (aliveDiff !== 0) return aliveDiff;
      const seenDiff = (b.lastSeenMinute ?? -1) - (a.lastSeenMinute ?? -1);
      if (seenDiff !== 0) return seenDiff;
      return (ATTITUDE_WEIGHT[b.attitude] ?? 0) - (ATTITUDE_WEIGHT[a.attitude] ?? 0);
    });
    const cast = ranked.slice(0, 8);
    paragraphs.push({ kind: "divider", text: "登场人物", nodeId: null });
    for (const p of cast) {
      const detailParts = [p.role.trim(), p.origin?.trim(), firstSentence(p.notes, 48).replace(/。$/, "")].filter(Boolean);
      const desc = detailParts.length ? detailParts.join("，") : "本局结识人物";
      const statusSuffix = `（与主角${p.attitude}${p.alive === false ? "，已故" : ""}）`;
      paragraphs.push({
        kind: "prose",
        text: ensureSentence(`${p.name}：${desc}${statusSuffix}`),
        nodeId: null,
      });
    }
  }

  return {
    index,
    kind: "preface",
    title: "卷首 · 人物与前情",
    chapterNumber: null,
    firstNodeId: null,
    lastNodeId: null,
    paragraphs,
    chars: paragraphs.reduce((sum, p) => sum + p.text.length, 0),
  };
}

function buildAppendixSection(
  index: number,
  state: WorldState,
  eraTitle: string,
  headClock: GameClock,
  savedChapters: Chapter[],
  chapterSections: NovelSection[],
  metaByNode: Map<string, NodeTimelineMeta>,
  statusLine: NovelStatusLine,
): NovelSection {
  const paragraphs: NovelParagraph[] = [];
  const protagonistName = state.protagonist.name || "无名氏";
  const startLabel = dateText(headClock, 0);
  const currentLabel = dateText(headClock, state.time.elapsedMinutes);

  paragraphs.push({
    kind: "prose",
    text: ensureSentence(`开局纪事：${startLabel}，${protagonistName}入${eraTitle}，行至${currentLabel}`),
    nodeId: null,
  });

  if (savedChapters.length > 0) {
    for (let i = 0; i < savedChapters.length; i++) {
      const c = savedChapters[i];
      const when = metaByNode.get(c.firstNodeId)?.dateLabel;
      const gist = firstSentence(c.gist || c.summary, 88);
      const heading = formatChapterHeading(i + 1, c.title);
      const text = gist
        ? `${heading}${when ? `（${when}）` : ""}：${gist}`
        : `${heading}${when ? `（${when}）` : ""}。`;
      paragraphs.push({ kind: "prose", text: ensureSentence(text), nodeId: c.firstNodeId });
    }
  } else if (chapterSections.length > 0) {
    for (const sec of chapterSections) {
      const when = sec.firstNodeId ? metaByNode.get(sec.firstNodeId)?.dateLabel : undefined;
      const where = sec.firstNodeId ? metaByNode.get(sec.firstNodeId)?.place : undefined;
      const detail = [when, where].filter(Boolean).join(" · ");
      paragraphs.push({
        kind: "prose",
        text: ensureSentence(`${sec.title}${detail ? `：记${detail}前后诸事` : ""}`),
        nodeId: sec.firstNodeId ?? null,
      });
    }
  }

  const completedGoals = state.goals.filter((g) => g.status === "完成");
  for (const g of completedGoals) {
    const when = g.endedMinute != null ? dateText(headClock, g.endedMinute) : null;
    const progress = g.progress.trim() ? `——${firstSentence(g.progress, 60)}` : "";
    paragraphs.push({
      kind: "prose",
      text: ensureSentence(`功成之事${when ? `（${when}）` : ""}：达成「${g.name}」${progress}`),
      nodeId: null,
    });
  }

  if (state.era.mode !== "free" && state.deviations.length > 0) {
    for (const dev of state.deviations) {
      const clean = dev.trim();
      if (clean) {
        paragraphs.push({
          kind: "prose",
          text: ensureSentence(`史事变迁：${clean}`),
          nodeId: null,
        });
      }
    }
  }

  if (state.script) {
    const doneBeats = state.script.beats.filter((b) => b.status === "done");
    const totalBeats = state.script.beats.length;
    const allSettled = totalBeats > 0 && state.script.beats.every((b) => b.status !== "todo");
    const lineDesc = state.script.line.trim() ? `「${state.script.line.trim()}」` : "本局剧本";
    paragraphs.push({
      kind: "prose",
      text: ensureSentence(
        `剧本纪要：${lineDesc}已历 ${doneBeats.length}/${totalBeats} 幕${allSettled ? "，诸幕皆已落定" : "，仍在推进"}`,
      ),
      nodeId: null,
    });
  }

  if (state.challenge) {
    const ch = state.challenge;
    const outcomeLabel =
      ch.status === "won"
        ? "挑战功成"
        : ch.status === "lost"
          ? "挑战惜败"
          : ch.status === "abandoned"
            ? "中途罢手"
            : "挑战进行中";
    const detail = (ch.outcome || ch.progress || "").trim();
    paragraphs.push({
      kind: "prose",
      text: ensureSentence(`挑战结局：「${ch.goal}」——${outcomeLabel}${detail ? `（${detail.replace(/[。]+$/, "")}）` : ""}`),
      nodeId: null,
    });
  }

  paragraphs.push({
    kind: "prose",
    text: `卷末收束：${statusLine.replace(/^——\s*|\s*——$/g, "")}。`,
    nodeId: null,
  });

  return {
    index,
    kind: "appendix",
    title: "附录 · 本局大事纪年",
    chapterNumber: null,
    firstNodeId: null,
    lastNodeId: null,
    paragraphs,
    chars: paragraphs.reduce((sum, p) => sum + p.text.length, 0),
  };
}

export function determineNovelStatusLine(world: Pick<World, "settings">, state: WorldState): {
  dead: boolean;
  statusLine: NovelStatusLine;
} {
  const dead = state.protagonist.stats.health <= 0 && world.settings.difficulty !== "宽松";
  if (dead) {
    return { dead: true, statusLine: "—— 全书完 · 这一世终 ——" };
  }
  const scriptCompleted = Boolean(
    state.script &&
      state.script.beats.length > 0 &&
      state.script.beats.every((b) => b.status !== "todo"),
  );
  const challengeCompleted = Boolean(
    state.challenge && (state.challenge.status === "won" || state.challenge.status === "lost"),
  );
  if (scriptCompleted || challengeCompleted) {
    return { dead: false, statusLine: "—— 本卷完 ——" };
  }
  return { dead: false, statusLine: "—— 未完待续 ——" };
}

/** Builds a clean chaptered `NovelBook` from a saved world's current (or specified) line. */
export async function buildNovelBook(
  repo: Repo,
  worldId: string,
  opts: NovelOptions = {},
): Promise<NovelBook | null> {
  const world = await repo.getWorld(worldId);
  if (!world) return null;
  const targetLineId = opts.lineId ?? world.currentLineId;
  if (!targetLineId) return null;
  const line = await repo.getLine(targetLineId);
  if (!line || line.worldId !== worldId) return null;

  const [path, rawChapters, state, clocks] = await Promise.all([
    repo.path(line.nodeId),
    repo.chaptersOnPath(worldId, line.nodeId),
    repo.getState(line.nodeId),
    repo.clocksOnPath(line.nodeId),
  ]);
  if (!path.length) return null;

  const openingNode = path[0];
  const openingState =
    openingNode && openingNode.id !== line.nodeId
      ? await repo.getState(openingNode.id).catch(() => state)
      : state;

  const includeActions = opts.includeActions ?? false;
  const includePreface = opts.includePreface ?? true;
  const includeChronicle = opts.includeChronicle ?? true;
  const chapterEvery = Math.max(6, Math.floor(opts.chapterEvery ?? 10));

  const era = eraContext(world.eraId, state);
  const { dead, statusLine } = determineNovelStatusLine(world, state);
  const seal = lifeSeal(state, dead);
  const metaByNode = computeNodeMeta(world, path, state, openingState, clocks);

  // Keep non-interrupted narrative nodes (`opening`, `turn`, `fastforward`) in path order.
  const pathPos = new Map(path.map((n, i) => [n.id, i]));
  const storyNodes = path.filter(
    (n) => n.kind !== "edit" && (n.status !== "interrupted" || Boolean(n.narrative.trim())),
  );

  // Map saved chapters onto `storyNodes` indices without dropping `fastforward` nodes inside ranges.
  interface ResolvedChapterSpan {
    startIdx: number;
    endIdx: number;
    chapter: Chapter;
  }
  const resolvedSpans: ResolvedChapterSpan[] = [];
  for (const ch of rawChapters) {
    const firstPathPos = pathPos.get(ch.firstNodeId);
    const lastPathPos = pathPos.get(ch.lastNodeId);
    if (firstPathPos === undefined || lastPathPos === undefined || firstPathPos > lastPathPos) continue;
    let startIdx = -1;
    let endIdx = -1;
    for (let i = 0; i < storyNodes.length; i++) {
      const p = pathPos.get(storyNodes[i].id)!;
      if (p >= firstPathPos && p <= lastPathPos) {
        if (startIdx < 0) startIdx = i;
        endIdx = i;
      }
    }
    if (startIdx >= 0 && endIdx >= startIdx) {
      const clampedStart = resolvedSpans.length
        ? Math.max(startIdx, resolvedSpans[resolvedSpans.length - 1].endIdx + 1)
        : startIdx;
      if (clampedStart <= endIdx) {
        resolvedSpans.push({ startIdx: clampedStart, endIdx, chapter: ch });
      }
    }
  }

  const sections: NovelSection[] = [];
  const usedAutoTitles = new Set<string>();
  for (const rs of resolvedSpans) {
    const cleaned = stripChapterPrefix(rs.chapter.title);
    if (cleaned) usedAutoTitles.add(cleaned);
  }

  if (includePreface) {
    sections.push(
      buildPrefaceSection(sections.length, state, era.clock, era.title, era.currency, dead),
    );
  }

  // Decide whether `storyNodes[0]` (`opening`) is rendered as `楔子` or absorbed into `chapters[0]`.
  let cursor = 0;
  const firstIsOpening = storyNodes[0]?.kind === "opening";
  const firstChapterStartsAtOpening = resolvedSpans[0]?.startIdx === 0;

  if (firstIsOpening && !firstChapterStartsAtOpening) {
    const openingParas = buildSectionParagraphs([storyNodes[0]], metaByNode, includeActions);
    if (openingParas.length > 0) {
      const openMeta = metaByNode.get(storyNodes[0].id);
      const subtitle = [openMeta?.dateLabel, openMeta?.place].filter(Boolean).join(" · ") || undefined;
      sections.push({
        index: sections.length,
        kind: "prologue",
        title: "楔子",
        ...(subtitle ? { subtitle } : {}),
        chapterNumber: null,
        autoGenerated: false,
        firstNodeId: storyNodes[0].id,
        lastNodeId: storyNodes[0].id,
        paragraphs: openingParas,
        chars: openingParas.reduce((sum, p) => sum + p.text.length, 0),
      });
    }
    cursor = 1;
  }

  let chapterCounter = 0;
  const pushAutoChapters = (sliceStart: number, sliceEndExclusive: number) => {
    for (let i = sliceStart; i < sliceEndExclusive; i += chapterEvery) {
      const slice = storyNodes.slice(i, Math.min(sliceEndExclusive, i + chapterEvery));
      const paras = buildSectionParagraphs(slice, metaByNode, includeActions);
      if (!paras.length) continue;
      chapterCounter++;
      const shortTitle = deriveAutoChapterTitle(chapterCounter, slice, metaByNode, usedAutoTitles);
      const m = metaByNode.get(slice[0].id);
      const subtitle = [m?.dateLabel, m?.place].filter(Boolean).join(" · ") || undefined;
      sections.push({
        index: sections.length,
        kind: "chapter",
        title: formatChapterHeading(chapterCounter, shortTitle),
        ...(subtitle ? { subtitle } : {}),
        chapterNumber: chapterCounter,
        autoGenerated: true,
        firstNodeId: slice[0].id,
        lastNodeId: slice[slice.length - 1].id,
        paragraphs: paras,
        chars: paras.reduce((sum, p) => sum + p.text.length, 0),
      });
    }
  };

  for (const span of resolvedSpans) {
    if (cursor < span.startIdx) {
      pushAutoChapters(cursor, span.startIdx);
    }
    const slice = storyNodes.slice(span.startIdx, span.endIdx + 1);
    const paras = buildSectionParagraphs(slice, metaByNode, includeActions);
    if (paras.length > 0) {
      chapterCounter++;
      const m = metaByNode.get(slice[0].id);
      const subtitle = [m?.dateLabel, m?.place].filter(Boolean).join(" · ") || undefined;
      sections.push({
        index: sections.length,
        kind: "chapter",
        title: formatChapterHeading(chapterCounter, span.chapter.title),
        ...(subtitle ? { subtitle } : {}),
        chapterNumber: chapterCounter,
        autoGenerated: false,
        firstNodeId: slice[0].id,
        lastNodeId: slice[slice.length - 1].id,
        paragraphs: paras,
        chars: paras.reduce((sum, p) => sum + p.text.length, 0),
      });
    }
    cursor = span.endIdx + 1;
  }

  if (cursor < storyNodes.length) {
    pushAutoChapters(cursor, storyNodes.length);
  }

  const chapterSections = sections.filter((s) => s.kind === "chapter");
  const validSavedChapters = resolvedSpans.map((s) => s.chapter);

  if (includeChronicle) {
    sections.push(
      buildAppendixSection(
        sections.length,
        state,
        era.title,
        era.clock,
        validSavedChapters,
        chapterSections,
        metaByNode,
        statusLine,
      ),
    );
  }

  // Re-index sequentially just in case.
  sections.forEach((s, idx) => {
    s.index = idx;
  });

  const protagonistName = state.protagonist.name.trim() || "无名氏";
  const startText = state.time.start.trim() || dateText(era.clock, 0);
  const whoAndWhen = [protagonistName, startText].filter(Boolean).join(" · ");
  const subtitle = `${whoAndWhen}${line.name !== "主线" ? `　（${line.name}）` : ""}`;
  const turnCount = storyNodes.filter((n) => n.kind === "turn" || n.kind === "fastforward").length;
  const totalChars = sections.reduce((sum, s) => sum + s.chars, 0);

  return {
    worldId: world.id,
    lineId: line.id,
    lineName: line.name,
    title: world.title,
    subtitle,
    author: `${protagonistName} 传`,
    eraTitle: era.title,
    seal,
    statusLine,
    generatedAt: new Date().toISOString(),
    turnCount,
    chapterCount: chapterSections.length,
    totalChars,
    sections,
  };
}

/** Formats a `NovelBook` as a traditional Chinese plain-text novel compatible with `parseBook`, Legado, and Koodo. */
export function formatNovelTxt(book: NovelBook): string {
  const out: string[] = [`《${book.title}》`];
  if (book.subtitle) out.push(book.subtitle);

  for (const section of book.sections) {
    out.push("", "", section.title, "");
    const rendered = section.paragraphs.map((p) => {
      if (p.kind === "divider") {
        return p.text === "◇" ? `${FULLWIDTH_INDENT}◇` : `${FULLWIDTH_INDENT}◇ ${p.text} ◇`;
      }
      if (p.kind === "action") {
        return `◇ ${p.text}`;
      }
      return `${FULLWIDTH_INDENT}${p.text}`;
    });
    if (rendered.length) out.push(rendered.join("\n\n"));
  }

  out.push("", "", book.statusLine, "");
  return out.join("\n");
}

/** Formats a `NovelBook` as clean GitHub-flavored Markdown. */
export function formatNovelMarkdown(book: NovelBook): string {
  const out: string[] = [`# 《${book.title}》`];
  if (book.subtitle) out.push("", `> ${book.subtitle}`);

  for (const section of book.sections) {
    out.push("", `## ${section.title}`);
    if (section.subtitle) out.push("", `*${section.subtitle}*`);
    for (const p of section.paragraphs) {
      if (p.kind === "divider") {
        out.push("", p.text === "◇" ? "* * *" : `*—— ${p.text} ——*`);
      } else if (p.kind === "action") {
        out.push("", `> ${p.text}`);
      } else {
        out.push("", p.text);
      }
    }
  }

  out.push("", "---", "", `*${book.statusLine}*`, "");
  return out.join("\n");
}

/** Produces a filesystem-safe download filename for a novel export. */
export function novelFileName(title: string, ext: "epub" | "txt" | "md"): string {
  const safe = title
    .replace(/[\\/:*?"<>|\x00-\x1f]/g, "")
    .replace(/\s+/g, " ")
    .replace(/[. ]+$/g, "")
    .trim() || "故事";
  return `${safe}.${ext}`;
}
